import numpy as np, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
plt.rcParams.update({"font.family":"serif","mathtext.fontset":"cm"})
T,N,O,G,I,B="#17A199","#1F3864","#E8762C","#F0B323","#222E2D","#3B5BA9"
def base(ax,xl,yl,xt,yt):
    ax.set_xlim(*xl);ax.set_ylim(*yl);ax.grid(alpha=0.3,lw=0.6);ax.set_xticks(xt);ax.set_yticks(yt)
    for s in("top","right"):ax.spines[s].set_visible(False)
    ax.spines["left"].set_position(("data",0));ax.spines["bottom"].set_position(("data",0))
    ax.tick_params(labelsize=8,colors=I)
    ax.plot(1,0,">k",transform=ax.get_yaxis_transform(),clip_on=False,ms=4)
    ax.plot(0,1,"^k",transform=ax.get_xaxis_transform(),clip_on=False,ms=4)
# fig 1: slant asymptote  r(x)=(x^2+3x-1)/(x-1)=x+4+3/(x-1)
fig,ax=plt.subplots(figsize=(4.1,3.1));fig.patch.set_alpha(0);ax.patch.set_alpha(0)
x1=np.linspace(-9,0.85,300);x2=np.linspace(1.2,9,300)
r=lambda x:(x**2+3*x-1)/(x-1)
for x in(x1,x2):ax.plot(x,r(x),color=N,lw=2.2)
xs=np.linspace(-9,9,2);ax.plot(xs,xs+4,color=O,lw=1.6,ls="--")
ax.axvline(1,color=T,lw=1.4,ls=":")
base(ax,(-9,9),(-12,22),[-8,-4,4,8],[-10,10,20])
ax.text(-8.6,6,r"$y=x+4$",color=O,fontsize=10.5,ha="left")
ax.text(1.4,-8.8,r"$x=1$",color=T,fontsize=10.5)
ax.text(5.2,21,r"$r(x)$",color=N,fontsize=10.5,va="top")
fig.tight_layout();fig.savefig("figs/AP1-11_slant.png",dpi=300,transparent=True)
# fig 2: transformations of sqrt(x)
fig,axs=plt.subplots(1,2,figsize=(4.1,3.1));fig.patch.set_alpha(0)
x=np.linspace(0,16,300)
for ax in axs:ax.patch.set_alpha(0)
ax=axs[0];ax.plot(x,np.sqrt(x),color=N,lw=2.2);ax.plot(x,-2*np.sqrt(x),color=O,lw=2.0)
ax.scatter([4,4],[2,-4],color=[N,O],s=30,zorder=6)
base(ax,(-1,16),(-9,5),[4,8,12],[-8,-4,4]);ax.set_title(r"$g(x)=-2f(x)$",fontsize=9.5,color=I)
ax.text(7.5,1.0,r"$f$",color=N,fontsize=10);ax.text(6.5,-6.2,r"$g$",color=O,fontsize=10)
ax=axs[1];ax.plot(x,np.sqrt(x),color=N,lw=2.2);xx=np.linspace(0,16,300);ax.plot(xx,np.sqrt(xx/3),color=O,lw=2.0)
ax.scatter([4,12],[2,2],color=[N,O],s=30,zorder=6)
base(ax,(-1,16),(-1,5),[4,8,12],[1,2,3,4]);ax.set_title(r"$h(x)=f\!\left(\frac{x}{3}\right)$",fontsize=9.5,color=I)
ax.text(1.0,2.6,r"$f$",color=N,fontsize=10);ax.text(13.2,2.5,r"$h$",color=O,fontsize=10)
fig.tight_layout();fig.savefig("figs/AP1-12_dilate.png",dpi=300,transparent=True)
# fig 3: models
fig,axs=plt.subplots(1,2,figsize=(4.1,3.1));fig.patch.set_alpha(0)
for ax in axs:ax.patch.set_alpha(0)
ax=axs[0];xs=np.arange(0,6);ax.scatter(xs,4*xs+3,color=O,s=30,zorder=6);ax.plot([0,5],[3,23],color=N,lw=2)
base(ax,(-0.7,5.7),(-1,26),[1,3,5],[5,10,15,20]);ax.set_title(r"constant $\Delta y$: linear",fontsize=9.5,color=I)
ax=axs[1];xs=np.arange(0,5);ax.scatter(xs,2*xs**2+xs+2,color=O,s=30,zorder=6);xx=np.linspace(0,4,100);ax.plot(xx,2*xx**2+xx+2,color=N,lw=2)
base(ax,(-0.6,4.7),(-3,42),[1,2,3,4],[10,20,30,40]);ax.set_title(r"constant $\Delta^{2}y$: quadratic",fontsize=9.5,color=I)
fig.tight_layout();fig.savefig("figs/AP1-13_models.png",dpi=300,transparent=True)
